# دریافت تعداد جابه‌جایی‌ها
n = int(input())  # تعداد جابه‌جایی‌ها

# مکان اولیه نخود
pea_position = 1  # نخود زیر کاسه 1 است

# پردازش جابه‌جایی‌ها
for _ in range(n):
    a, b = map(int, input().split())  # دریافت کاسه‌های جابه‌جا شده
    # اگر یکی از کاسه‌ها شامل کاسه‌ای باشد که نخود زیر آن است، مکان نخود را تغییر می‌دهیم
    if pea_position == a:
        pea_position = b  # نخود به کاسه b منتقل می‌شود
    elif pea_position == b:
        pea_position = a  # نخود به کاسه a منتقل می‌شود

# چاپ مکان نهایی کاسه‌ای که نخود زیر آن است
print(pea_position)

